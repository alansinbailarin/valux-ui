/**
 * Node module customization hook used ONLY by scripts/verify-conditions.mjs's
 * react-server smoke test (registered via --import, react-server condition
 * runs only).
 *
 * Plain Node has no notion of the "use client" directive — a real RSC
 * bundler (webpack/turbopack) stops tracing a module's own imports the
 * moment it sees the directive and swaps in a client-reference stub, so
 * hooks like useEffect/useState never get statically linked against the
 * react-server export condition of `react` (which doesn't provide them).
 * Node's ESM loader, left to its own devices, eagerly *links* every
 * transitively-imported binding regardless of directives, so a package
 * that correctly ships "use client" on every interactive component would
 * still fail this smoke test for a reason a real consumer would never hit.
 *
 * This hook approximates the bundler behavior: when a module under dist/
 * starts with "use client", replace its body with an inert stand-in that
 * exposes the same export names but never evaluates the original source,
 * so its own imports are never walked.
 */
const CLIENT_DIRECTIVE_RE = /^\s*["']use client["'];?/;
const EXPORT_LIST_RE = /^export\s*\{([^}]*)\};?\s*$/gm;
const VALID_IDENTIFIER_RE = /^[A-Za-z_$][\w$]*$/;

function extractExportNames(source) {
  const names = new Set();
  for (const match of source.matchAll(EXPORT_LIST_RE)) {
    for (const entry of match[1].split(",")) {
      const trimmed = entry.trim();
      if (!trimmed) continue;
      const aliasMatch = trimmed.match(/^(\S+)\s+as\s+(\S+)$/);
      names.add(aliasMatch ? aliasMatch[2] : trimmed);
    }
  }
  return names;
}

function buildClientStub(exportNames, url) {
  const lines = [
    `// Stub generated by scripts/rsc-boundary-loader.mjs for ${url}`,
    `// This module starts with "use client"; a real RSC bundler would`,
    `// never trace its imports from the server graph, so we don't either.`,
  ];
  for (const name of exportNames) {
    lines.push(
      `export function ${name}() { throw new Error(${JSON.stringify(
        `${name} is a client-reference stub (react-server smoke test) and cannot be invoked on the server.`,
      )}); }`,
    );
  }
  if (exportNames.size === 0) lines.push("export {};");
  return lines.join("\n");
}

export async function load(url, context, nextLoad) {
  if (!url.includes("/dist/")) return nextLoad(url, context);

  const result = await nextLoad(url, context);
  if (result.format !== "module") return result;

  const source = result.source ? result.source.toString() : "";
  if (!CLIENT_DIRECTIVE_RE.test(source)) return result;

  const exportNames = extractExportNames(source);
  if ([...exportNames].some((name) => !VALID_IDENTIFIER_RE.test(name))) {
    // Unexpected export shape (alias/default) — bail out to real source
    // rather than silently mis-stubbing it.
    return result;
  }

  return {
    format: "module",
    shortCircuit: true,
    source: buildClientStub(exportNames, url),
  };
}
